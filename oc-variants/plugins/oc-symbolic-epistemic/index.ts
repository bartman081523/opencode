function flagOn(name: string): boolean {
  const v = process.env[name]
  if (v === undefined || v === null) return false
  const s = String(v).trim().toLowerCase()
  return s === "1" || s === "true" || s === "yes" || s === "on"
}

function masterOn(): boolean {
  if (process.env["OC_SYMBOLIC_EPISTEMIC"] !== undefined) return flagOn("OC_SYMBOLIC_EPISTEMIC")
  return true
}

function partOn(name: string): boolean {
  if (process.env[name] === undefined) return true
  return flagOn(name)
}

export default Plugin.define({
  id: "oc-symbolic-epistemic",
  async setup(ctx) {
    await ctx.session.hook("context", (event) => {
      if (!masterOn()) return
      if (partOn("OC_EPISTEMIC")) event.system.push({ type: "text", text: EPISTEMIC_PREAMBLE })
      if (partOn("OC_SCIMIND")) event.system.push({ type: "text", text: SCIMIND_MANDATES })
      if (partOn("OC_EPISTEMIC")) event.system.push({ type: "text", text: DO_NOT_SURFACE })
    })
  },
})
